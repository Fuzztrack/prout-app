// i18n-js v4: `missingTranslation` est un registre (avec `.get()`), pas un callback.
// Si on l'écrase par une fonction, `i18n.t()` plante avec "missingTranslation.get is not a function".
// On enregistre donc eine stratégie custom qui renvoie simplement la clé.
i18n.missingTranslation.register('key', (_i18n, scope) => {
  const key = Array.isArray(scope) ? scope.join('.') : String(scope);
  console.warn(`[i18n] Traduction manquante: ${key}`);
  return key;
});
i18n.missingBehavior = 'key';

// Funktion für eine robuste Erkennung der Gerätesprache
function getDeviceLanguage(): string {
  try {
    const locales = getLocales();
    if (!locales || locales.length === 0) {
      return 'en';
    }

    const firstLocale = locales[0];

    // Auf iOS 'locale' verwenden, falls verfügbar, sonst 'languageCode'
    let languageCode = firstLocale.languageCode;

    // Falls wir eine vollständige Locale haben (z. B. "en-US"), den Basis-Sprachcode extrahieren
    if (firstLocale.languageTag) {
      const baseLanguage = firstLocale.languageTag.split(/[-_]/)[0];
      languageCode = baseLanguage;
    } else if (firstLocale.languageCode) {
      // Falls languageCode einen Bindestrich/Unterstrich enthält (z. B. "en-US" / "fr_FR"),
      // den Teil vor dem Trenner extrahieren.
      languageCode = firstLocale.languageCode.split(/[-_]/)[0];
    }

    // Unterstützte Sprachen mappen
    const supportedLanguages = ['fr', 'en', 'es', 'pt', 'de', 'it'];
    const detectedLanguage = languageCode?.toLowerCase() || 'en';

    // Falls die erkannte Sprache unterstützt wird, diese verwenden
    if (supportedLanguages.includes(detectedLanguage)) {
      // 'pt' auf 'pt-BR' mappen
      if (detectedLanguage === 'pt') {
        return 'pt-BR';
      }
      return detectedLanguage;
    }

    // Spezifische Überprüfungen nach Präfix
    if (detectedLanguage.startsWith('en')) {
      return 'en';
    }

    if (detectedLanguage.startsWith('fr')) {
      return 'fr';
    }

    if (detectedLanguage.startsWith('es')) {
      return 'es';
    }

    if (detectedLanguage.startsWith('pt')) {
      return 'pt-BR';
    }

    if (detectedLanguage.startsWith('de')) {
      return 'de';
    }

    if (detectedLanguage.startsWith('it')) {
      return 'it';
    }

    // Fallback auf Englisch
    return 'en';
  } catch (error) {
    console.error('❌ Fehler bei der Spracherkennung:', error);
    return 'en';
  }
}

// Gerätesprache abrufen
const deviceLanguage = getDeviceLanguage();
i18n.locale = deviceLanguage;

